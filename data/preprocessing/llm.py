"""
LLM data preprocessing utilities
"""

import numpy as np
import pandas as pd
from typing import Tuple

from .prior import UNSW_NB15_PriorPreprocessor, CIC_IDS_2017_PriorPreprocessor, NSL_KDD_PriorPreprocessor, BotNetIoT_L01_PriorPreprocessor

class LLMDataPreprocessor:
    def __init__(self, dataset: str, llm: object):
        if dataset == "UNSW_NB15":
            self.prior_preprocessor = UNSW_NB15_PriorPreprocessor
        elif dataset == "CIC_IDS_2017":
            self.prior_preprocessor = CIC_IDS_2017_PriorPreprocessor
        elif dataset == "NSL_KDD":
            self.prior_preprocessor = NSL_KDD_PriorPreprocessor
        elif dataset == "BotNetIoT_L01":
            self.prior_preprocessor = BotNetIoT_L01_PriorPreprocessor
        else:
            raise ValueError(f"Unsupported dataset name: {dataset}")
        
        # Initialize the LLM instance
        self.llm = llm

    def binary_LLM_preprocessing(self, train_df: pd.DataFrame, test_df: pd.DataFrame, target_col: str = 'label') -> Tuple[pd.DataFrame, pd.Series, pd.DataFrame, pd.Series]:
        """
        Preprocess the data using the generated cleaning function.

        Args:
            train_df (pd.DataFrame): Training data with 'label' column.
            test_df (pd.DataFrame): Test data with 'label' column.

        Returns:
            Tuple: (train_processed, train_label, test_processed, test_label)
        """
        # 1. Prior preprocessing (drops id/attack_cat; service '-' → 'other')
        train_data = self.prior_preprocessor.binary_prior_preprocessing(train_df.copy())
        test_data = self.prior_preprocessor.binary_prior_preprocessing(test_df.copy())

        # 2. Drop label
        train_label = train_data.pop(target_col)
        test_label = test_data.pop(target_col)

        # 3. Null value handling for service
        if 'service' in train_data.columns:
            train_data['service'] = train_data['service'].replace('-', 'other')
        if 'service' in test_data.columns:
            test_data['service'] = test_data['service'].replace('-', np.nan)

        # 4. Call the (method-agnostic) generated cleaning function. It also performs class-imbalance
        #    resampling on the training set, so it returns a (possibly) resampled train_label aligned
        #    with train_processed. The reduction method itself is chosen and generated by the LLM and
        #    applied later in pipeline._reduce_features. `reduction_method` is kept only for caller
        #    compatibility and is no longer used here.
        train_processed, train_label, test_processed = self.llm.preprocess_data(train_data, test_data, train_label)

        return train_processed, train_label, test_processed, test_label

    def multi_class_LLM_preprocessing(self, train_df: pd.DataFrame, test_df: pd.DataFrame, target_col: str = 'attack_cat') -> Tuple[pd.DataFrame, pd.Series, pd.DataFrame, pd.Series]:
        """
        Preprocess the data using the generated cleaning function.

        Args:
            train_df (pd.DataFrame): Training data with 'attack_cat' column.
            test_df (pd.DataFrame): Test data with 'attack_cat' column.

        Returns:
            Tuple: (train_processed, train_label, test_processed, test_label)
        """

        # 1. Prior preprocessing (drops id/label; service '-' → 'other')
        train_data = self.prior_preprocessor.multi_class_prior_preprocessing(train_df.copy())
        test_data = self.prior_preprocessor.multi_class_prior_preprocessing(test_df.copy())

        # 2. Drop label
        train_label = train_data.pop(target_col)
        test_label = test_data.pop(target_col)

        # 3. Null value handling for service
        if 'service' in train_data.columns:
            train_data['service'] = train_data['service'].replace('-', 'other')
        if 'service' in test_data.columns:
            test_data['service'] = test_data['service'].replace('-', np.nan)

        # 4. Call the (method-agnostic) generated cleaning function. It also performs class-imbalance
        #    resampling on the training set, so it returns a (possibly) resampled train_label aligned
        #    with train_processed. The reduction method itself is chosen and generated by the LLM and
        #    applied later in pipeline._reduce_features. `reduction_method` is kept only for caller
        #    compatibility and is no longer used here.
        train_processed, train_label, test_processed = self.llm.preprocess_data(train_data, test_data, train_label)

        return train_processed, train_label, test_processed, test_label